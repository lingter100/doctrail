test('real Java: failed PDF retry, oversized validation, keyboard focus and current-session expiry', async ({ page }) => {
  await register(page.request);
  await ready(page);
  await page.locator('#upload').click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.locator('#upload')).toBeFocused();
  await page.keyboard.press('/');
  await expect(page.locator('#search-input')).toBeFocused();
  await page.locator('#upload').click();
  await page.getByRole('dialog').getByLabel('업로드할 문서 파일').setInputFiles({ name: 'synthetic-large.txt', mimeType: 'text/plain', buffer: Buffer.alloc(5 * 1024 * 1024 + 1, 97) });
  const uploads: string[] = [];
  const watch = (request: import('@playwright/test').Request) => {
    if (request.method() === 'POST' && /\/documents$/.test(new URL(request.url()).pathname)) uploads.push(request.url());
  };
  page.on('request', watch);
  await page.getByRole('dialog').getByRole('button', { name: '업로드', exact: true }).click();
  await expect(page.getByRole('dialog').locator('.form-error')).toContainText('5MB 이하');
  expect(uploads).toEqual([]);
  page.off('request', watch);
  await page.getByRole('dialog').getByLabel('업로드할 문서 파일').setInputFiles({ name: 'synthetic-broken.pdf', mimeType: 'application/pdf', buffer: Buffer.from('synthetic invalid PDF') });
  await page.getByRole('dialog').getByRole('button', { name: '업로드', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.locator('.status-badge.failed')).toContainText('처리 실패');
  await expect(page.locator('.source-warning')).toContainText('이 문서는 아직 검색할 수 없어요');
  const retried = page.waitForResponse(response => response.url().endsWith('/reprocess'));
  await page.getByRole('button', { name: '다시 처리하기', exact: true }).click();
  expect((await retried).status()).toBe(200);
  await expect(page.locator('.source-badges')).toContainText('버전 2');
  await expect(page.locator('.status-badge.failed')).toContainText('처리 실패');
  await page.context().clearCookies();
  await search(page, 'synthetic-current-expired');
  await expect(page.locator('#auth-form')).toBeVisible();
  await expect(page.locator('.source-pane, #workspace-select, [data-document], .result-card')).toHaveCount(0);
  expect((await page.request.get('/api/auth/me')).status()).toBe(401);
});

test('real Java: separate member session cannot see private documents or owner controls', async ({ page, playwright, baseURL }) => {
  const owner = await playwright.request.newContext({ baseURL });
  try {
    const ownerAuth = await register(owner, 'Synthetic shared workspace');
    const workspace = ownerAuth.workspaces[0].id;
    const shared = await upload(owner, workspace, 'Synthetic shared policy', 'commonmarker shared evidence');
    const hidden = await upload(owner, workspace, 'Synthetic private policy', 'privatemarker commonmarker private evidence', 'private');
    const member = await register(page.request, 'Synthetic member workspace');
    expect((await owner.post(`/api/workspaces/${workspace}/members`, { data: { email: member.user.email } })).status()).toBe(201);
    await ready(page);
    await page.locator('#workspace-select').selectOption(workspace);
    await expect(page.locator(`[data-document="${shared.id}"]`)).toBeVisible();
    await expect(page.locator(`[data-document="${hidden.id}"]`)).toHaveCount(0);
    await expect(page.locator('#members')).toHaveCount(0);
    await completedSearch(page, 'commonmarker');
    await expect(page.locator('.result-card')).toHaveCount(1);
    await expect(page.locator('.result-card')).toContainText(shared.title);
    await page.locator('[data-hit="0"]').click();
    await expect(page.locator('#source-text')).toContainText('shared evidence');
    await expect(page.locator('#edit-document, #delete-document')).toHaveCount(0);
    await completedSearch(page, 'privatemarker');
    await expect(page.locator('.result-card')).toHaveCount(0);
    expect((await page.request.get(`/api/documents/${hidden.id}`)).status()).toBe(404);
    expect((await page.request.put(`/api/documents/${shared.id}`, { data: { title: 'Forbidden edit', content: 'forbidden', visibility: 'workspace' } })).status()).toBe(403);
    expect((await page.request.delete(`/api/documents/${shared.id}`)).status()).toBe(403);
    expect((await page.request.post(`/api/workspaces/${workspace}/members`, { data: { email: ownerAuth.user.email } })).status()).toBe(403);
  } finally { await owner.dispose(); }
});
